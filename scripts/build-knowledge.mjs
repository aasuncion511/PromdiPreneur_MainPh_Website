// Builds the Ask PromdiPreneur knowledge index from knowledge/manifest.json.
// Only documents with status "approved" are included. Each "## Page N" (or "## Heading") block becomes one chunk.
// Output: server/generated/knowledge.ts (committed, so tests and Netlify Functions read the same data).
//   npm run build:knowledge
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const kdir = join(root, 'knowledge');
const manifest = JSON.parse(readFileSync(join(kdir, 'manifest.json'), 'utf8'));
const sources = JSON.parse(readFileSync(join(kdir, 'official-sources.json'), 'utf8'));

const MAX_CHUNK = 2600; // characters; long pages are split on blank lines
const chunks = [];
const docs = [];
for (const d of manifest.documents) {
  if (d.status !== 'approved') continue;
  docs.push({ id: d.id, title: d.title, version: d.version, regulatoryReviewPending: !!d.regulatoryReviewPending });
  const text = readFileSync(join(kdir, d.file), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  for (const block of text.split(/^## /m).slice(1)) {
    const nl = block.indexOf('\n');
    const heading = block.slice(0, nl).trim();
    if ((d.excludeHeadings ?? []).includes(heading)) continue;
    const pageNo = Number(heading.replace(/\D+/g, '')) || 0;
    const fromNo = Number(String(d.downweightHeadingsFrom ?? '').replace(/\D+/g, '')) || Infinity;
    const weight = pageNo >= fromNo ? 0.5 : 1;
    let body = block.slice(nl + 1).trim();
    while (body.length) {
      let cut = body.length <= MAX_CHUNK ? body.length : body.lastIndexOf('\n\n', MAX_CHUNK);
      if (cut < MAX_CHUNK / 2) cut = Math.min(body.length, MAX_CHUNK);
      const part = body.slice(0, cut).trim();
      if (part.length > 60) chunks.push({ doc: d.id, ref: `${d.title}, ${heading}`, text: part, weight });
      body = body.slice(cut).trim();
    }
  }
}

mkdirSync(join(root, 'server', 'generated'), { recursive: true });
const out = `// GENERATED by scripts/build-knowledge.mjs from knowledge/ — do not edit by hand.
export const KNOWLEDGE_DOCS = ${JSON.stringify(docs, null, 2)} as const;
export const KNOWLEDGE_CHUNKS: { doc: string; ref: string; text: string; weight: number }[] = ${JSON.stringify(chunks)};
export const OFFICIAL_SOURCES: { agency: string; topics: string[]; url: string; origin: string }[] = ${JSON.stringify(sources.sources, null, 2)};
export const LGU_NOTE = ${JSON.stringify(sources.lgu)};
`;
writeFileSync(join(root, 'server', 'generated', 'knowledge.ts'), out);
console.log(
  `knowledge: ${docs.length} approved document(s), ${chunks.length} chunks, ${sources.sources.length} official sources`
);
